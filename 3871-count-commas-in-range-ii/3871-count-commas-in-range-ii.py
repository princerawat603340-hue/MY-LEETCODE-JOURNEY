class Solution(object):
    def countCommas(self, n):
        """
        :type n: int
        :rtype: int
        """
        if n <1000:
            return 0
        elif 10**3<=n<10**6:
            return n-999
        elif 10**6<=n<10**9:
            return (n-999999)*2 + 999999-999
        elif 10**9<=n<10**12:
            return (n-999999999)*3 + (999999999-999999)*2 + 999999-999
        elif 10**12<=n<10**15:
            return (n-(10**12-1))*4 + ((10**12-1)-999999999)*3 + (999999999-999999)*2 + 999999-999
        else :
            return (n-(10**12-1))*4 + ((10**12-1)-999999999)*3 + (999999999-999999)*2 + 999999-999+1

        